// Return an array of fallback URLs for a given reciter and surah
export function getSurahAudioCandidates(reciter: Reciter, surahNumber: number): string[] {
  const pad3 = surahNumber.toString().padStart(3, '0');
  const num = surahNumber.toString();
  const list: string[] = [];

  // 1. Primary server configured
  if (reciter.id === 'mossad') {
    // Verified Abdulrahman Mossad full recordings on Internet Archive and fallbacks
    list.push(`https://archive.org/download/AMusad/${pad3}.mp3`);
    list.push(`https://dn710005.ca.archive.org/0/items/AMusad/${pad3}.mp3`);
    list.push(`https://dn710005.ca.archive.org/0/items/telawah-09/telawah%2009.mp3`);
    list.push(`https://archive.org/download/abdulrahman-mossad-beautiful-quran-recitation/${pad3}.mp3`);
    list.push(`https://download.quranicaudio.com/qdc/mishari_al_afasy/murattal/${num}.mp3`);
  } else {
    // If the server URL ends with a slash, test standard formats
    const base = reciter.serverUrl.endsWith('/') ? reciter.serverUrl : `${reciter.serverUrl}/`;
    
    // QDC format (1.mp3 or 001.mp3)
    if (base.includes('/qdc/')) {
      list.push(`${base}${num}.mp3`);
      list.push(`${base}${pad3}.mp3`);
    } else {
      list.push(`${base}${pad3}.mp3`);
      list.push(`${base}${num}.mp3`);
    }

    // Fast QuranicAudio / BunnyCDN fallback
    list.push(`https://download.quranicaudio.com/qdc/mishari_al_afasy/murattal/${num}.mp3`);
  }

  return list;
}

export function getSurahAudioUrl(reciterServerUrl: string, surahNumber: number): string {
  const padNumber = surahNumber.toString().padStart(3, '0');
  const num = surahNumber.toString();
  if (reciterServerUrl.includes('/qdc/')) {
    return `${reciterServerUrl}${num}.mp3`;
  }
  return `${reciterServerUrl}${padNumber}.mp3`;
}

export function getAyahAudioUrl(reciterFolder: string, surahNumber: number, ayahNumber: number): string {
  const surahPad = surahNumber.toString().padStart(3, '0');
  const ayahPad = ayahNumber.toString().padStart(3, '0');
  return `https://everyayah.com/data/${reciterFolder}/${surahPad}${ayahPad}.mp3`;
}

export function getSurahApproxSizeMb(numberOfAyahs: number): number {
  return Number((Math.max(1.2, (numberOfAyahs * 0.08) + 1.2)).toFixed(1));
}
